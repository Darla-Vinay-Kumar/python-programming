# =========================
# Python Variables
# =========================

# String
name = "Darla Vinay Kumar"

# Integer
age = 28

# Float
experience = 4.0

# Boolean
is_devops_engineer = True

# Multiple variables
first_name, last_name = "Darla", "Vinay Kumar"

# Same value assigned to multiple variables
x = y = z = 100

# Display values
print("Name:", name)
print("Age:", age)
print("Experience:", experience)
print("DevOps Engineer:", is_devops_engineer)

# Check data types
print(type(name))
print(type(age))
print(type(experience))
print(type(is_devops_engineer))

# Variable reassignment
age = 32
print("Updated age:", age)

# Dynamic typing
value = 100
print(value, type(value))

value = "Python"
print(value, type(value))